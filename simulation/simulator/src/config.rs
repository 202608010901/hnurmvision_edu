#[derive(Resource)]
pub struct ConfigWatcher {
    _watcher: RecommendedWatcher,
    receiver: Receiver<Result<Event, notify::Error>>,
}

pub struct ConfigPlugin;

impl Plugin for ConfigPlugin {
    fn build(&self, app: &mut App) {
        let config = SimulationConfig::default();

        // Set up file watcher using crossbeam-channel for thread safety
        let (tx, rx): (
            Sender<Result<Event, notify::Error>>,
            Receiver<Result<Event, notify::Error>>,
        ) = unbounded();
        let watcher_result = RecommendedWatcher::new(
            move |res| {
                let _ = tx.send(res);
            },
            notify::Config::default(),
        );

        match watcher_result {
            Ok(mut watcher) => {
                if let Err(e) = watcher.watch(Path::new("config.toml"), RecursiveMode::NonRecursive)
                {
                    warn!("Failed to watch config.toml: {}", e);
                } else {
                    info!("Config hot-reload enabled for config.toml");
                    app.insert_resource(ConfigWatcher {
                        _watcher: watcher,
                        receiver: rx,
                    });
                    app.add_systems(Update, config_hot_reload);
                }
            }
            Err(e) => {
                warn!("Failed to create config watcher: {}", e);
            }
        }

        app.insert_resource(config)
            .register_type::<SimulationConfig>();
    }
}

fn config_hot_reload(
    mut config: ResMut<SimulationConfig>,
    watcher: Option<Res<ConfigWatcher>>,
    mut substeps: Option<ResMut<SubstepCount>>,
    mut fixed_time: Option<ResMut<Time<Fixed>>>,
) {
    let Some(watcher) = watcher else {
        return;
    };

    // Non-blocking check for file changes
    while let Ok(Ok(event)) = watcher.receiver.try_recv() {
        if event.kind.is_modify() {
            match SimulationConfig::load() {
                Ok(new_config) => {
                    info!("Config reloaded successfully");
                    if let Some(substeps) = substeps.as_deref_mut() {
                        substeps.0 = new_config.physics.substep_count;
                    }
                    if let Some(fixed_time) = fixed_time.as_deref_mut() {
                        *fixed_time = Time::<Fixed>::from_hz(new_config.physics.fixed_hz.max(1.0));
                    }
                    *config = new_config;
                }
                Err(e) => {
                    warn!("Failed to reload config: {}", e);
                }
            }
        }
    }
}

/// Deterministic three-lane classroom scene, in Bevy world metres (Y up).
#[derive(Deserialize, Reflect, Clone)]
#[serde(default)]
pub struct TrainingConfig {
    /// Swept = authoritative finite-radius flight; Shadow logs an independent copy.
    pub hit_detection: crate::ballistics::HitDetectionMode,
    pub hit_debug: bool,
    pub damage_per_hit: f64,
    pub enabled: bool,
    pub observer: [f32; 3],
    pub targets_x: f32,
    pub targets_y: f32,
    pub lane_spacing: f32,
    /// Keep only the selected target in the arena; park the other two high above it, out
    /// of the camera's field of view and out of the firing line.
    ///
    /// A real vision stack meets one enemy at a time. The three-lane line-up is a
    /// classroom layout: it fills the frame with three cars, and a detector that picks the
    /// wrong one still looks like it is working. Parked cars are also unreachable, so a
    /// stray shot cannot be scored as a hit on a target nobody was aiming at.
    pub solo_target: bool,
    pub translation_amplitude: f32,
    pub translation_period: f32,
    pub rotation_speed: f32,
}
impl Default for TrainingConfig {
    fn default() -> Self {
        Self { hit_detection: crate::ballistics::HitDetectionMode::Swept, hit_debug: false,
            damage_per_hit: 10.0, enabled: false, observer: [-11.0, 0.01, 0.0], targets_x: -5.0,
            targets_y: 0.0, lane_spacing: 2.0, solo_target: true,
            translation_amplitude: 0.5,
            translation_period: 4.0, rotation_speed: 2.0 }
    }
}
