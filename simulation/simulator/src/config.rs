/// Camera-facing fidelity knobs: what a real vision stack would see, rather than what
/// looks right to a human eye. All of them default to "leave the render alone".
#[derive(Deserialize, Reflect, Clone)]
#[serde(default)]
pub struct VisionConfig {
    /// Multiplies the emissive term of every vehicle material. Real armour LEDs are
    /// blown out (the sensor saturates and the bar bleeds wider than its physical
    /// width); vehicle.glb's emissive alone renders them dim enough that a detector
    /// calibrated on real footage misses them. 1.0 = unchanged.
    pub armor_emissive_scale: f32,
    /// Bloom on the capture camera: the halo a real lens shows around blown-out LEDs.
    pub bloom_intensity: f32,
    /// Gaussian sensor noise in gray levels (0-255) added to published RGB8 frames.
    pub noise_sigma: f32,
}

impl Default for VisionConfig {
    fn default() -> Self {
        Self {
            armor_emissive_scale: 1.0,
            bloom_intensity: 0.0,
            noise_sigma: 0.0,
        }
    }
}

